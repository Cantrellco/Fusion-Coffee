#!/usr/bin/env node
// ============================================================
// Square Catalog → src/lib/square-catalog.json
//
// Pulls the shop's real catalog (items, size/variation prices, images) out of
// Square and writes it to a committed snapshot the static site builds against.
// This is what makes /merch sell REAL products at REAL prices without anyone
// hand-copying a price list — Square stays the single source of truth.
//
//   npm run sync:catalog            # uses .dev.vars / env
//   npm run sync:catalog -- --dry   # print what it found, write nothing
//   npm run sync:catalog -- --all   # don't filter to merch (name discovery)
//
// By default the snapshot keeps ONLY the products /merch actually sells. The
// shop's real catalog is ~200 items — the whole café menu, every bean, every
// seasonal drink — and `src/lib/catalog.ts` imports this file at module scope,
// so anything left in here ships to the browser. Use --all when you need to
// see the real catalog names in order to fill in a `squareName`.
//
// Reads (in order of precedence): process.env, then ./.dev.vars.
//   SQUARE_ACCESS_TOKEN   — needs the ITEMS_READ scope
//   SQUARE_ENVIRONMENT    — "sandbox" | "production" (default sandbox)
//
// READ-ONLY. This script never writes to Square; the worst it can do is
// overwrite the local snapshot, which is regenerated by running it again.
//
// ⚠️ The snapshot is only as current as the last run. Prices that change in
// Square show up on the site after a re-run + redeploy — OR immediately, via
// the live passthrough at functions/api/catalog.ts, which the shop page prefers
// when it is reachable. The snapshot is the offline floor, not the ceiling.
// ============================================================

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/lib/square-catalog.json');
const DRY = process.argv.includes('--dry');
const ALL = process.argv.includes('--all');

/**
 * The names /merch cares about, read straight out of the `merch` block in
 * site.ts — both the display `name` and any `squareName` override.
 *
 * Yes, this greps TypeScript. The alternative is a second copy of the product
 * list that silently drifts from the real one; a regex over a block we control
 * is the lesser evil. If it ever returns nothing we keep the whole catalog
 * rather than silently shipping an empty shop.
 */
function merchNamesFromSite() {
  try {
    const src = readFileSync(resolve(ROOT, 'src/lib/site.ts'), 'utf8');
    const block = src.match(/export const merch:[\s\S]*?\n\};/);
    if (!block) return null;
    const names = [...block[0].matchAll(/\b(?:squareName|name): '([^']+)'/g)].map(
      (m) => m[1],
    );
    return names.length ? new Set(names.map(matchKey)) : null;
  } catch {
    return null;
  }
}

/** Same normalization src/lib/catalog.ts uses to join the two sides. */
function matchKey(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '');
}

// ---- config ---------------------------------------------------------------

/** Parse a dotenv-style file into a plain object. Ignores comments/blank lines. */
function readEnvFile(path) {
  try {
    return Object.fromEntries(
      readFileSync(path, 'utf8')
        .split('\n')
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith('#'))
        .map((line) => {
          const eq = line.indexOf('=');
          if (eq === -1) return null;
          // Strip surrounding quotes — dotenv files often carry them.
          const value = line.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
          return [line.slice(0, eq).trim(), value];
        })
        .filter(Boolean),
    );
  } catch {
    return {};
  }
}

const fileEnv = readEnvFile(resolve(ROOT, '.dev.vars'));
const TOKEN = process.env.SQUARE_ACCESS_TOKEN || fileEnv.SQUARE_ACCESS_TOKEN;
const ENVIRONMENT =
  process.env.SQUARE_ENVIRONMENT || fileEnv.SQUARE_ENVIRONMENT || 'sandbox';
const BASE =
  ENVIRONMENT === 'production'
    ? 'https://connect.squareup.com'
    : 'https://connect.squareupsandbox.com';
const SQUARE_VERSION = '2025-10-16';

if (!TOKEN) {
  console.error(
    'No SQUARE_ACCESS_TOKEN found (checked process.env and .dev.vars).\n' +
      'Add a token with the ITEMS_READ scope, then re-run.',
  );
  process.exit(1);
}

// ---- fetch ----------------------------------------------------------------

/** One page of /v2/catalog/list. Square caps pages, so we follow the cursor. */
async function listPage(types, cursor) {
  const url = new URL(`${BASE}/v2/catalog/list`);
  url.searchParams.set('types', types);
  if (cursor) url.searchParams.set('cursor', cursor);
  const res = await fetch(url, {
    headers: {
      'Square-Version': SQUARE_VERSION,
      Authorization: `Bearer ${TOKEN}`,
    },
  });
  const data = await res.json();
  if (!res.ok) {
    const detail = data?.errors?.[0];
    throw new Error(
      `Square ${res.status}: ${detail?.code ?? 'unknown'} — ${
        detail?.detail ?? 'no detail'
      }`,
    );
  }
  return data;
}

async function listAll(types) {
  const objects = [];
  let cursor;
  do {
    const page = await listPage(types, cursor);
    objects.push(...(page.objects ?? []));
    cursor = page.cursor;
  } while (cursor);
  return objects;
}

// ---- map ------------------------------------------------------------------

const money = (m) => (typeof m?.amount === 'number' ? m.amount : null);

function build(objects) {
  const byId = new Map(objects.map((o) => [o.id, o]));

  const categoryName = (id) =>
    byId.get(id)?.category_data?.name ?? null;

  // IMAGE objects hold the CDN url; items reference them by id.
  const imageUrl = (id) => byId.get(id)?.image_data?.url ?? null;

  const products = objects
    .filter((o) => o.type === 'ITEM' && !o.is_deleted)
    .map((o) => {
      const item = o.item_data ?? {};

      // Square moved to `categories` (many) but still sets `category_id` (one)
      // on older catalogs — read both so either vintage maps correctly.
      const categoryIds = [
        ...(item.categories ?? []).map((c) => c.id),
        ...(item.category_id ? [item.category_id] : []),
      ];
      const categories = [...new Set(categoryIds.map(categoryName).filter(Boolean))];

      const images = [
        ...(item.image_ids ?? []),
        ...(item.image_id ? [item.image_id] : []),
      ]
        .map(imageUrl)
        .filter(Boolean);

      const variations = (item.variations ?? [])
        .filter((v) => !v.is_deleted)
        .map((v) => {
          const d = v.item_variation_data ?? {};
          return {
            id: v.id,
            name: d.name ?? 'Regular',
            priceCents: money(d.price_money),
            sku: d.sku ?? null,
            ordinal: d.ordinal ?? 0,
            // VARIABLE_PRICING items have no price in the catalog — they can't
            // be sold online, so the site marks them unavailable rather than
            // guessing a number.
            variablePricing: d.pricing_type === 'VARIABLE_PRICING',
          };
        })
        .sort((a, b) => a.ordinal - b.ordinal);

      return {
        squareItemId: o.id,
        name: item.name ?? '',
        description: item.description_plaintext ?? item.description ?? null,
        categories,
        images,
        variations,
        modifierListIds: (item.modifier_list_info ?? [])
          .filter((m) => m.enabled !== false)
          .map((m) => m.modifier_list_id),
        // An item is sellable online only if at least one variation carries a
        // real fixed price.
        sellable: variations.some(
          (v) => !v.variablePricing && typeof v.priceCents === 'number',
        ),
      };
    })
    .filter((p) => p.name)
    .sort((a, b) => a.name.localeCompare(b.name));

  const modifierLists = objects
    .filter((o) => o.type === 'MODIFIER_LIST' && !o.is_deleted)
    .map((o) => {
      const d = o.modifier_list_data ?? {};
      return {
        id: o.id,
        name: d.name ?? '',
        selectionType: d.selection_type ?? 'SINGLE',
        modifiers: (d.modifiers ?? [])
          .filter((m) => !m.is_deleted)
          .map((m) => ({
            id: m.id,
            name: m.modifier_data?.name ?? '',
            priceCents: money(m.modifier_data?.price_money) ?? 0,
            ordinal: m.modifier_data?.ordinal ?? 0,
          }))
          .sort((a, b) => a.ordinal - b.ordinal),
      };
    });

  return { products, modifierLists };
}

// ---- run ------------------------------------------------------------------

const objects = await listAll(
  'ITEM,ITEM_VARIATION,CATEGORY,IMAGE,MODIFIER_LIST',
);
const built = build(objects);
const { modifierLists } = built;

const wanted = ALL ? null : merchNamesFromSite();
const products = wanted
  ? built.products.filter((p) => wanted.has(matchKey(p.name)))
  : built.products;
const dropped = built.products.length - products.length;

const snapshot = {
  // Stamped so the site (and a human reading the diff) can see how stale it is.
  syncedAt: new Date().toISOString(),
  environment: ENVIRONMENT,
  products,
  modifierLists,
};

const sellable = products.filter((p) => p.sellable);
console.log(
  `Square catalog (${ENVIRONMENT}): ${products.length} items, ` +
    `${sellable.length} sellable, ${modifierLists.length} modifier lists.` +
    (dropped > 0 ? ` (${dropped} non-merch items filtered out — --all to keep)` : ''),
);
for (const p of products) {
  const prices = p.variations
    .map((v) =>
      v.priceCents == null ? `${v.name}: —` : `${v.name}: $${(v.priceCents / 100).toFixed(2)}`,
    )
    .join(', ');
  console.log(`  ${p.sellable ? '✓' : '·'} ${p.name}${prices ? ` — ${prices}` : ''}`);
}

if (products.length === 0) {
  console.log(
    '\nCatalog is empty. If this is the sandbox, that is expected — the real\n' +
      'items live in the shop\'s PRODUCTION Square account. Re-run with a\n' +
      'production token (ITEMS_READ) to pull the actual merch and prices.',
  );
}

if (DRY) {
  console.log('\n--dry: nothing written.');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`\nWrote ${OUT.replace(`${ROOT}/`, '')}`);
}
